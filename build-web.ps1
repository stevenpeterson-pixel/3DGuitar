# icons (drawn here so there is nothing to download)
Add-Type -AssemblyName System.Drawing
function New-Icon([int]$n, [string]$path, [bool]$square) {
  $bmp = New-Object System.Drawing.Bitmap $n, $n; $g = [System.Drawing.Graphics]::FromImage($bmp); $g.SmoothingMode = 'AntiAlias'; $k = $n / 256.0
  $brush = New-Object System.Drawing.Drawing2D.LinearGradientBrush ([System.Drawing.PointF]::new(0, 0)), ([System.Drawing.PointF]::new(0, $n)), ([System.Drawing.Color]::FromArgb(255, 58, 36, 20)), ([System.Drawing.Color]::FromArgb(255, 14, 9, 6))
  if ($square) { $g.FillRectangle($brush, 0, 0, $n, $n) } else {
    $g.Clear([System.Drawing.Color]::Transparent); $p = New-Object System.Drawing.Drawing2D.GraphicsPath; $r = 54 * $k; $d = 2 * $r; $w = $n - 1
    $p.AddArc(0, 0, $d, $d, 180, 90); $p.AddArc($w - $d, 0, $d, $d, 270, 90); $p.AddArc($w - $d, $w - $d, $d, $d, 0, 90); $p.AddArc(0, $w - $d, $d, $d, 90, 90); $p.CloseFigure(); $g.FillPath($brush, $p) }
  $gold = [System.Drawing.Color]::FromArgb(255, 222, 184, 110); $pale = [System.Drawing.Color]::FromArgb(255, 243, 223, 174); $c = $n / 2.0
  $g.DrawEllipse((New-Object System.Drawing.Pen $gold, (16 * $k)), $c - 84 * $k, $c - 84 * $k, 168 * $k, 168 * $k)
  $g.DrawEllipse((New-Object System.Drawing.Pen $pale, (4 * $k)), $c - 104 * $k, $c - 104 * $k, 208 * $k, 208 * $k)
  $g.FillEllipse((New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 9, 6, 4))), $c - 66 * $k, $c - 66 * $k, 132 * $k, 132 * $k)
  $ps = New-Object System.Drawing.Pen $pale, (3.2 * $k); for ($i = 0; $i -lt 6; $i++) { $y = $c + ($i - 2.5) * 17 * $k; $g.DrawLine($ps, 10 * $k, $y, $n - 10 * $k, $y) }
  $g.Dispose(); $bmp.Save($path, [System.Drawing.Imaging.ImageFormat]::Png); $bmp.Dispose()
}
New-Icon 192 (Join-Path $out 'icons\icon-192.png') $false
